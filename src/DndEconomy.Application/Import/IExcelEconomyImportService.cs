namespace DndEconomy.Application.Import;

/// <summary>
/// Сервис первичной загрузки "Модели" предметов — исходной таблицы экономики — в БД.
/// Доступен администратору через отдельный экран загрузки файла.
/// </summary>
public interface IExcelEconomyImportService
{
  /// <summary>
  /// Разбирает загруженный .xlsx (листы "Предметы", "Города", "Сезонность", "Настройки")
  /// и создаёт соответствующие записи в БД. Существующие записи с тем же ключом обновляются,
  /// а не дублируются, поэтому файл можно перезаливать при правках. Файл не обязан содержать
  /// все четыре листа сразу — каждый импортируется независимо, если он есть в книге, поэтому
  /// можно загружать как один общий файл, так и четыре отдельных (по одному листу в каждом),
  /// см. шаблоны в /templates.
  /// </summary>
  /// <param name="fileStream">Поток содержимого .xlsx файла.</param>
  /// <param name="cancellationToken">Токен отмены.</param>
  Task<EconomyImportSummary> ImportAsync(Stream fileStream, CancellationToken cancellationToken);
}
