namespace DndEconomy.Domain.Enums;

/// <summary>
/// Категория населённого пункта. Влияет на то, какие товары в нём в принципе доступны
/// (например, огнестрельное оружие продаётся только в крупных городах).
/// </summary>
public enum CitySize
{
  /// <summary>Деревня — минимальный ассортимент.</summary>
  Village = 0,

  /// <summary>Обычный город.</summary>
  Town = 1,

  /// <summary>Крупный город — максимальный ассортимент, включая редкие и футуристичные товары.</summary>
  Metropolis = 2
}
